    for group, label, adversarial in [(INJECTION, "injection", False), (ADVERSARIAL, "injection", True),
                                      (SUSPICIOUS, "suspicious", False), (BENIGN, "benign", False)]:
        for i, (text, technique) in enumerate(group):
            out.append({"text": text, "technique": [technique], "context": CONTEXTS[(i + len(out)) % len(CONTEXTS)],
                        "label": label, "source": "written", "adversarial": adversarial})
    return out
