"""python -m extension.build [--api https://your-host] — generate the extension's shared code and icons.

gen.js is built from scanner/extract.js and rules/score.py so the extension and the server can never disagree
about what a ghost is or how it scores. Load the extension/ folder unpacked in Chrome after running this.
"""
import json
import struct
import sys
import zlib
from pathlib import Path

from rules.score import INJECTION, PATTERNS, SUSPICIOUS

HERE = Path(__file__).parent
ROOT = HERE.parent
GHOST = ["....####....", "..########..", ".##########.", ".##oo##oo##.", ".##oo##oo##.", "############",
         "############", "############", "############", "############", "##.###.###.#", "#...#...#..."]


def png(size: int) -> bytes:
    """The pixel ghost as a PNG, with only zlib: bone body, red eyes, transparent background."""
    scale = size // 12
    rows = []
    for y in range(size):
        row = bytearray([0])
        for x in range(size):
            c = GHOST[min(y // scale, 11)][min(x // scale, 11)]
            row += bytes((236, 228, 214, 255) if c == "#" else (224, 20, 47, 255) if c == "o" else (0, 0, 0, 0))
        rows.append(bytes(row))
    chunk = lambda t, d: struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d))
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", size, size, 8, 6, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(b"".join(rows))) + chunk(b"IEND", b""))


def main(argv: list[str]) -> None:
    api = argv[argv.index("--api") + 1].rstrip("/") if "--api" in argv else "http://localhost:8000"
    extract = (ROOT / "scanner" / "extract.js").read_text(encoding="utf-8").strip().rstrip(";")
    rules = [[p, w, r] for p, w, r in PATTERNS]
    (HERE / "gen.js").write_text(
        "// Generated by extension/build.py from scanner/extract.js and rules/score.py. Do not edit.\n"
        f"const GHOST_API = {json.dumps(api)};\n"
        f"const GHOST_RULES = {json.dumps(rules)};\n"
        f"const GHOST_LIMITS = {json.dumps({'injection': INJECTION, 'suspicious': SUSPICIOUS})};\n"
        f"const ghostExtract = {extract};\n", encoding="utf-8")
    for size in (16, 48, 128):
        (HERE / f"icon{size}.png").write_bytes(png(size if size % 12 == 0 else 12 * (size // 12 + 1)))
    manifest = json.loads((HERE / "manifest.json").read_text(encoding="utf-8"))
    manifest["host_permissions"] = [api + "/*"]
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"built extension/ for {api}")


if __name__ == "__main__":
    main(sys.argv[1:])
